#!/usr/bin/env python3
"""Keep Jauria's own package versions in sync; never edit dependency versions."""
import argparse
import datetime
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
DESKTOP = Path('experiments/tauri-vertical/desktop')
RUNNER = Path('experiments/tauri-vertical/runner')
SEMVER = re.compile(r'(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(?:-([0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*))?')


def valid_version(value):
    match = SEMVER.fullmatch(value)
    return bool(match) and not any(part.isdigit() and len(part) > 1 and part[0] == '0'
                                   for part in (match.group(4) or '').split('.'))


def render(root, version):
    """Prepare all edits before writing; dependencies and schema stay unchanged."""
    edits = {Path('VERSION'): version + '\n'}
    for relative in (DESKTOP / 'package.json', DESKTOP / 'package-lock.json', DESKTOP / 'src-tauri/tauri.conf.json'):
        data = json.loads((root / relative).read_text())
        data['version'] = version
        if relative.name == 'package-lock.json':
            data['packages']['']['version'] = version
        edits[relative] = json.dumps(data, ensure_ascii=False, indent=2) + '\n'
    for directory, name in ((RUNNER, 'aw-runner'), (DESKTOP / 'src-tauri', 'aw-vertical-desktop')):
        relative = directory / 'Cargo.toml'
        text = (root / relative).read_text()
        text, count = re.subn(r'(?m)^(version\s*=\s*)"[^"]+"', lambda m: m[1] + '"' + version + '"', text, count=1)
        if count != 1:
            raise ValueError('Missing package version: ' + str(relative))
        edits[relative] = text
        relative = directory / 'Cargo.lock'
        text = (root / relative).read_text()
        pattern = r'(\[\[package\]\]\nname = "' + re.escape(name) + r'"\nversion = )"[^"]+"'
        text, count = re.subn(pattern, lambda m: m[1] + '"' + version + '"', text)
        if count != 1:
            raise ValueError('Missing or duplicate own package: ' + str(relative))
        edits[relative] = text
    edits[DESKTOP / 'src/app-version.ts'] = (
        '// Generated by scripts/version.py; VERSION is the source of truth.\n'
        "export const appVersion = '" + version + "';\n")
    return edits


def check(root, version):
    errors = []
    for relative, expected in render(root, version).items():
        path = root / relative
        if not path.is_file():
            errors.append(str(relative))
        elif relative.suffix == '.json':
            if json.loads(path.read_text()) != json.loads(expected):
                errors.append(str(relative))
        elif path.read_text() != expected:
            errors.append(str(relative))
    changelog = (root / 'CHANGELOG.md').read_text()
    heading = re.search(r'^## \[' + re.escape(version) + r'\] - (\d{4}-\d{2}-\d{2})$', changelog, re.M)
    if not heading or '## [Unreleased]' not in changelog:
        errors.append('CHANGELOG.md: release entry or Unreleased missing')
    else:
        try:
            datetime.date.fromisoformat(heading[1])
        except ValueError:
            errors.append('CHANGELOG.md: invalid release date')
    return errors


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--check', action='store_true')
    group.add_argument('--set', metavar='VERSION')
    args = parser.parse_args()
    version = args.set if args.set is not None else (ROOT / 'VERSION').read_text().strip()
    if not valid_version(version):
        parser.error('Expected MAJOR.MINOR.PATCH with an optional prerelease, e.g. 0.1.1 or 0.2.0-beta.1')
    if args.set is not None:
        for relative, content in render(ROOT, version).items():
            (ROOT / relative).write_text(content)
        print('Version synchronized: ' + version + '. Add its dated entry to CHANGELOG.md before building.')
    else:
        errors = check(ROOT, version)
        if errors:
            parser.exit(1, 'Version validation failed:\n- ' + '\n- '.join(errors) + '\n')
        print('Version and changelog verified: ' + version)


if __name__ == '__main__':
    main()
