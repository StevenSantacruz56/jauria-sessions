import assert from 'node:assert/strict';
import { inputFrames, OrderedInput } from '../src/input.ts';

const text = 'acción 中文 🙂\n'.repeat(6000);
const frames = inputFrames(text);
assert.equal(frames.join(''), text);
assert.ok(frames.length > 1 && frames.every(frame => new TextEncoder().encode(frame).length <= 16384));
assert.ok(frames.every(frame => new TextDecoder('utf-8', { fatal: true }).decode(new TextEncoder().encode(frame)) === frame));
let release!: () => void; const first = new Promise<void>(resolve => release = resolve);
const sent: string[] = [];
const queue = new OrderedInput(async frame => { sent.push(frame); if (frame === 'first') await first; }, () => assert.fail('unexpected failure'));
const a = queue.enqueue('first'); const b = queue.enqueue('second');
await Promise.resolve(); await Promise.resolve();
assert.deepEqual(sent, ['first']); release(); await Promise.all([a,b]);
assert.deepEqual(sent, ['first','second']);
let attempts = 0; let reported = 0;
const broken = new OrderedInput(async () => { attempts++; throw new Error('uncertain delivery'); }, () => reported++);
const results = await Promise.allSettled([broken.enqueue('one'), broken.enqueue('two')]);
assert.ok(results.every(result => result.status === 'rejected'));
await assert.rejects(broken.enqueue('three'));
assert.equal(attempts, 1); assert.equal(reported, 1);
let releasePaste!: () => void;
const pastePending = new Promise<void>(resolve => releasePaste = resolve);
const ordered: string[] = [];
const controls = new OrderedInput(async frame => { ordered.push(frame); if (ordered.length === 1) await pastePending; }, () => assert.fail('unexpected failure'));
const paste = controls.enqueue('x'.repeat(16385));
const interrupt = controls.control(async () => { ordered.push('interrupt'); });
const next = controls.enqueue('after');
await Promise.resolve(); await Promise.resolve();
assert.equal(ordered.length, 1);
releasePaste(); await Promise.all([paste, interrupt, next]);
assert.deepEqual(ordered.map(frame => frame.length > 100 ? 'paste frame' : frame), ['paste frame', 'x', 'interrupt', 'after']);
let interrupted = false;
const uncertain = new OrderedInput(async () => { throw new Error('uncertain paste'); }, () => {});
await Promise.allSettled([uncertain.enqueue('paste'), uncertain.control(async () => { interrupted = true; })]);
assert.equal(interrupted, false);
await assert.rejects(uncertain.control(async () => {}));
console.log('5 input checks passed: UTF8 framing, FIFO, suspend after uncertain delivery, native interrupt after paste, no interrupt after failed delivery');
