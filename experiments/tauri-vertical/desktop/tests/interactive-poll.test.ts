import assert from 'node:assert/strict';
import { InteractivePoll } from '../src/interactive-poll.ts';
let now = 0;
const poll = new InteractivePoll(() => now);
assert.equal(poll.delay(true), 150);
assert.equal(poll.isTyping(true), false);
const sleeping = poll.wait(true);
poll.activity();
await sleeping; // Input wakes the existing awaited sleep, not another poll.
assert.equal(poll.delay(true), 12);
assert.equal(poll.delay(false), 150);
assert.equal(poll.isTyping(true), true);
assert.equal(poll.isTyping(false), false);
now = 1199;
assert.equal(poll.delay(true), 12);
poll.activity();
now = 1201;
assert.equal(poll.delay(true), 12);
now = 2400;
assert.equal(poll.delay(true), 150);
poll.output();
assert.equal(poll.delay(true), 33);
assert.equal(poll.delay(false), 150);
now = 2501;
assert.equal(poll.delay(true), 150, 'periodic output does not hold the typing-speed loop');
poll.activity(); poll.output();
assert.equal(poll.delay(true), 12, 'output cannot shorten the typing window');
now = 3702;
await poll.wait(true); // Timed idle wait also clears its wake callback.
const backgroundPage = poll.wait(true);
poll.wakeUp();
await backgroundPage;
assert.equal(poll.isTyping(true), false, 'backfill wake does not pretend to be keyboard activity');
poll.activity();
console.log('PASS interactive polling: immediate wake, bounded activity window, background/idle backoff');
